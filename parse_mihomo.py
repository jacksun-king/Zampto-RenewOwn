#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
解析 Shadowsocks(ss://) 节点链接，生成 mihomo (clash-meta) 配置。
本地 mixed 监听 127.0.0.1:1080（socks5+http 通用），续期脚本无需改动。

支持：
  ss://BASE64(method:password)@server:port/?plugin=obfs%3Btls%3Bhost%3Dxxx

用法：
  GOST_PROXY="ss://..." python3 parse_mihomo.py   # 生成 mihomo_config.yaml
"""
import base64
import os
import sys
import urllib.parse

LOCAL_PORT = int(os.environ.get("LOCAL_PROXY_PORT", "1080"))


def b64decode(s: str) -> str:
    s = s.strip()
    if not s:
        return ""
    padding = 4 - len(s) % 4
    if padding != 4:
        s += "=" * padding
    try:
        return base64.b64decode(s).decode("utf-8")
    except Exception:
        return ""


def parse_ss(uri: str) -> dict:
    """解析 ss:// 链接。兼容 SIP002（userinfo 为 base64(method:password)）和
    传统格式（userinfo 为明文 method:password）。"""
    body = uri[len("ss://"):]
    # 去掉 fragment（节点名）
    name = ""
    if "#" in body:
        body, name = body.split("#", 1)
    # 分离 query（plugin 参数）
    qs_str = ""
    if "?" in body:
        body, qs_str = body.split("?", 1)
    qs = urllib.parse.parse_qs(qs_str) if qs_str else {}
    # userinfo@host:port
    if "@" not in body:
        raise SystemExit("❌ ss:// 链接缺少 @，无法解析 server")
    userinfo, hostport = body.rsplit("@", 1)
    hostport = hostport.rstrip("/")
    if ":" in hostport:
        server, port_str = hostport.rsplit(":", 1)
        port = int(port_str) if port_str.isdigit() else 443
    else:
        server, port = hostport, 443
    # userinfo: base64(method:password) 或明文 method:password
    method, password = "", ""
    decoded = b64decode(userinfo)
    if ":" in decoded:
        method, password = decoded.split(":", 1)
    elif ":" in userinfo:
        method, password = userinfo.split(":", 1)
    if not method or not password:
        raise SystemExit(f"❌ 无法解析 ss:// userinfo: {userinfo}")
    plugin_opts = qs.get("plugin", [None])[0]
    return {"name": urllib.parse.unquote(name) or "ss-node",
            "server": server, "port": port,
            "method": method, "password": password,
            "plugin_opts": plugin_opts}


def plugin_to_mihomo(plugin_opts: str) -> dict:
    """把 plugin=obfs%3Btls%3Bhost%3Dxxx 转成 mihomo plugin 块。"""
    out = {}
    if not plugin_opts:
        return out
    parts = urllib.parse.unquote(plugin_opts).split(";")
    kind = parts[0] if parts else ""
    if kind == "obfs":
        out["plugin"] = "obfs"
        opts = {}
        for p in parts[1:]:
            if "=" in p:
                k, v = p.split("=", 1)
                opts[k] = v
        # mihomo 的 obfs 用 plugin-opts: mode: tls; host: xxx
        mode = opts.get("mode", "tls")
        host = opts.get("host", "")
        # host 可能带端口（默认 443），mihomo 接受 host:port 形式
        out["plugin-opts"] = {"mode": mode, "host": host} if host else {"mode": mode}
    return out


def build_config(node: dict) -> dict:
    """生成 mihomo 配置：mode=global 强制全走该节点，mixed 监听本地端口。"""
    p = {"name": node["name"], "type": "ss",
         "server": node["server"], "port": node["port"],
         "cipher": node["method"], "password": node["password"]}
    p.update(plugin_to_mihomo(node.get("plugin_opts")))
    return {
        "mixed-port": LOCAL_PORT,
        "allow-lan": False,
        "mode": "global",
        "log-level": "error",
        "external-controller": "127.0.0.1:9090",
        "proxies": [p],
    }


def main():
    proxy = os.environ.get("GOST_PROXY", "")
    if not proxy:
        raise SystemExit("❌ 未设置 GOST_PROXY（ss:// 链接）")
    node = parse_ss(proxy)
    cfg = build_config(node)
    with open("mihomo_config.yaml", "w", encoding="utf-8") as f:
        f.write("# generated by parse_mihomo.py\n")
        f.write(f"mixed-port: {LOCAL_PORT}\n")
        f.write("allow-lan: false\n")
        f.write("mode: global\n")
        f.write("log-level: error\n")
        f.write("external-controller: 127.0.0.1:9090\n\n")
        f.write("proxies:\n")
        for k, v in node.items():
            if k in ("name", "server", "port", "method", "password"):
                f.write(f"  - name: {v}\n" if k == "name" else f"    {k}: {v}\n")
        p = plugin_to_mihomo(node.get("plugin_opts"))
        if p.get("plugin"):
            f.write(f"    plugin: {p['plugin']}\n")
            opts = p.get("plugin-opts", {})
            f.write("    plugin-opts:\n")
            for k, v in opts.items():
                f.write(f"      {k}: {v}\n")
    print(f"✅ mihomo_config.yaml 已生成（节点 {node['name']} → {node['server']}:{node['port']}）")


if __name__ == "__main__":
    main()
